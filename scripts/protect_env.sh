#!/usr/bin/env bash
# protect_env.sh - Prevent .env files from being committed
# Usage: ./protect_env.sh [--install] [--check]

set -euo pipefail

PROTECTED_PATTERNS=(
    '.env'
    '.env.*'
    '*.env'
    '*.pem'
    '*.key'
    '*.crt'
    '*.p12'
    '*.pfx'
    'id_rsa*'
    'id_ed25519*'
    '*.secret'
    '*.token'
)

check_staged() {
    local violations=0
    echo "Checking staged files for secrets..."

    for pattern in "${PROTECTED_PATTERNS[@]}"; do
        if git diff --cached --name-only | grep -E "$pattern" >/dev/null; then
            echo "ERROR: Staged file matches protected pattern '$pattern':"
            git diff --cached --name-only | grep -E "$pattern" | sed 's/^/  /'
            violations=$((violations + 1))
        fi
    done

    return $violations
}

check_committed() {
    local violations=0
    echo "Checking committed files for secrets..."

    for pattern in "${PROTECTED_PATTERNS[@]}"; do
        if git ls-files | grep -E "$pattern" >/dev/null; then
            echo "ERROR: Tracked file matches protected pattern '$pattern':"
            git ls-files | grep -E "$pattern" | sed 's/^/  /'
            violations=$((violations + 1))
        fi
    done

    return $violations
}

scan_content() {
    local violations=0
    echo "Scanning file content for potential secrets..."

    local secret_patterns=(
        'password\s*=\s*[^#\s]{8,}'
        'secret\s*=\s*[^#\s]{16,}'
        'token\s*=\s*[^#\s]{16,}'
        'api[_-]?key\s*=\s*[^#\s]{16,}'
        'private[_-]?key'
        '-----BEGIN (RSA |EC |OPENSSH )?PRIVATE KEY-----'
        'mongodb://[^:]+:[^@]+@'
        'postgresql://[^:]+:[^@]+@'
        'mysql://[^:]+:[^@]+@'
        'redis://:[^@]+@'
    )

    for pattern in "${secret_patterns[@]}"; do
        if git diff --cached | grep -iE "$pattern" >/dev/null; then
            echo "WARNING: Potential secret detected in staged changes (pattern: $pattern)"
            violations=$((violations + 1))
        fi
    done

    return $violations
}

install_hook() {
    local hook_file=".git/hooks/pre-commit"
    cat > "$hook_file" <<'EOF'
#!/usr/bin/env bash
# Auto-generated by protect_env.sh --install
set -euo pipefail
exec "$(git rev-parse --show-toplevel)/protect_env.sh" --check
EOF
    chmod +x "$hook_file"
    echo "Installed pre-commit hook at $hook_file"
}

main() {
    case "${1:-}" in
        --install)
            install_hook
            ;;
        --check|"")
            check_staged || exit 1
            check_committed || exit 1
            scan_content || exit 1
            echo "All checks passed."
            ;;
        *)
            echo "Usage: $0 [--install|--check]"
            echo "  --install  Install as git pre-commit hook"
            echo "  --check    Run checks (default)"
            exit 1
            ;;
    esac
}

main "$@"